/** 스테이지/구장 등 데이터 문자열 매핑 (영문 원본 → 한국어) */
const STAGE_KO: Dict = {
  Final: "결승",
  "Group Stage": "조별리그",
  "Round of 16": "16강",
  "Round of 32": "32강",
  "Quarter-final": "8강",
  "Semi-final": "4강",
};

export function t(lang: Lang, key: string): string {
  return DICTS[lang]?.[key] ?? DICTS.en[key] ?? key;
}

export function stageLabel(lang: Lang, stage: string): string {
  return lang === "ko" ? STAGE_KO[stage] ?? stage : stage;
}

/** 선수/팀 표시명 — 한국어일 때 nameKo 우선 */
export function displayName(lang: Lang, name: string, nameKo?: string): string {
  return lang === "ko" && nameKo ? nameKo : name;
}
